const dict: Record<Locale, Strings> = { en, tr, ar };
export type HomeKey = keyof Strings;
export const ht = (locale: Locale, k: HomeKey, vars: Record<string, string> = {}) =>
  Object.entries(vars).reduce((s, [name, v]) => s.replace(`{${name}}`, v), dict[locale]?.[k] ?? en[k]);
